"""One-off generator for sql/01_profile_views.sql (deterministic, no timestamps)."""

DATE_RE = r"^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01])$"
NUM_RE = r"^[+-]?(\d+\.?\d*|\.\d+)$"

COLS = {
    "orders_clean": [
        "order_id", "customer_id", "product_id", "order_date:D",
        "quantity:N", "unit_price_paid:N", "discount:N", "payment_mode",
        "order_status", "delivery_days:N", "notes", "raw_order_id",
        "raw_customer_id", "raw_product_id", "raw_order_date",
        "raw_quantity", "raw_unit_price_paid", "raw_discount",
        "raw_payment_mode", "raw_order_status", "raw_delivery_days",
        "raw_notes", "_source_row", "source_file", "source_row_number",
        "dedup_rule_applied", "rules_passed", "rules_failed",
    ],
    "customers_master": [
        "customer_id", "customer_name", "email:E", "city", "phone",
        "signup_date:D", "raw_customer_id", "raw_customer_name",
        "raw_email", "raw_city", "raw_phone", "raw_signup_date",
        "_source_row", "source_file", "source_row_number",
        "dedup_rule_applied", "rules_passed", "rules_failed",
    ],
    "products_clean": [
        "product_id", "product_name", "category", "unit_price:N",
        "stock_qty:N", "raw_product_id", "raw_product_name",
        "raw_category", "raw_unit_price", "raw_stock_qty", "_source_row",
        "source_file", "source_row_number", "dedup_rule_applied",
        "rules_passed", "rules_failed",
    ],
}


def _branch(table, spec):
    name, _, kind = spec.partition(":")
    miss = f"WHEN NULLIF(TRIM({name}), '') IS NULL"
    if kind == "D":
        gate = ("WHEN\n"
                f"                TRIM({name})\n"
                f"                !~ '{DATE_RE}'\n"
                "                THEN 1")
    elif kind == "N":
        gate = ("WHEN\n"
                f"                TRIM({name})\n"
                f"                !~ '{NUM_RE}'\n"
                "                THEN 1")
    elif kind == "E":
        gate = f"WHEN TRIM({name}) NOT LIKE '%@%.%' THEN 1"
    else:
        return [
            "SELECT",
            f"    '{table}' AS tbl,",
            f"    '{name}' AS column_name,",
            "    COUNT(*) AS n_rows,",
            "    SUM(",
            "        CASE",
            f"            {miss} THEN 1",
            "            ELSE 0",
            "        END",
            "    ) AS n_missing,",
            "    0 AS n_unusable,",
            "    SUM(",
            "        CASE",
            f"            {miss} THEN 0",
            "            ELSE 1",
            "        END",
            "    ) AS n_usable",
            f"FROM {table}",
        ]
    use = gate.replace("THEN 1", "THEN 0")
    return [
        "SELECT",
        f"    '{table}' AS tbl,",
        f"    '{name}' AS column_name,",
        "    COUNT(*) AS n_rows,",
        "    SUM(",
        "        CASE",
        f"            {miss} THEN 1",
        "            ELSE 0",
        "        END",
        "    ) AS n_missing,",
        "    SUM(",
        "        CASE",
        f"            {miss} THEN 0",
        f"            {gate}",
        "            ELSE 0",
        "        END",
        "    ) AS n_unusable,",
        "    SUM(",
        "        CASE",
        f"            {miss} THEN 0",
        f"            {use}",
        "            ELSE 1",
        "        END",
        "    ) AS n_usable",
        f"FROM {table}",
    ]


def main():
    from pathlib import Path

    from src.path_guard import assert_inside_write_root

    lines = [
        "-- 01_profile_views.sql : one row per staging column.",
        "-- GENERATED by gen01.py — edit the generator, not this file.",
        "-- n_missing = NULL or blank; n_unusable = non-blank failing the",
        "-- column regex gate (ISO date, plain numeric, email @-check);",
        "-- text columns gate nothing. n_usable = rows - missing -",
        "-- unusable, so the three always sum to rows. Gates mirror",
        "-- src/normalise.py and the 08 rule-view regexes.",
        "CREATE OR REPLACE VIEW v_column_profile AS",
    ]
    first = True
    for table, specs in COLS.items():
        for spec in specs:
            if not first:
                lines.append("UNION ALL")
            first = False
            lines += _branch(table, spec)
    lines[-1] = lines[-1] + ";"
    lines.append("")
    target = assert_inside_write_root(
        Path(__file__).resolve().parent / "sql" / "01_profile_views.sql")
    target.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"branches={sum(len(v) for v in COLS.values())} "
          f"lines={len(lines)} maxlen={max(len(x) for x in lines)}")


if __name__ == "__main__":
    main()
